#!/usr/bin/env python3
"""Generate the two T12 reference files.

``rev_results_t12_law.json``
    One independent realisation of the distribution-free null law of the scaled
    Hoeffding statistic, stored as a monotone quantile grid.  This is the reference used
    for the KS distance of T12 (the published tail table is not a distribution function,
    see Section 2.5 of the manuscript).  The run is long: ``n_law = 2,000`` with
    ``N = 200,000`` replications takes roughly 110 minutes on one core, which is why the
    grid is committed rather than regenerated by the verification suite.

``rev_results_t12_diag.json``
    The T12 diagnostic table of the manuscript: KS distance to the independent reference
    and the rejection rate from the published critical value, at each sample size of the
    Study 1 grid, using the same study seed.

Run from the package root::

    python3 code/gen_t12_law.py            # long: regenerates the reference first
    python3 code/gen_t12_law.py --diag-only  # reuse the committed reference

Consumed by ``code/verify_manuscript.py`` and reported in Sections 2.5 and 5.1.1.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import time

import numpy as np
from scipy import stats as st

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import core  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SEED_LAW = 20241231          # disjoint from every study seed
N_LAW = 200_000
N_LAW_N = 2_000
SEED_DIAG = 2024             # the Study 1 seed
NS_DIAG = (5, 10, 20, 30, 50, 100, 200, 500)
N_DIAG = 10_000
OUT_DIR = ROOT
WORKDIR = ROOT


def _apply_outdir(path):
    """Redirect the results directory, creating it if necessary.

    Args:
        path: directory to write results into.

    Returns:
        str: the absolute path that results will be written to.
    """
    global OUT_DIR, WORKDIR
    OUT_DIR = WORKDIR = os.path.abspath(path)
    os.makedirs(OUT_DIR, exist_ok=True)
    return OUT_DIR


def build_law():
    """Simulate the limit law and write ``rev_results_t12_law.json``."""
    t0 = time.time()
    rng = np.random.default_rng(SEED_LAW)
    v = core.mc_hoeffding_d(N_LAW_N, N_LAW, dep="indep", rng=rng)
    v = np.sort(v[np.isfinite(v)])
    p = np.concatenate([[0.0], np.linspace(0.0005, 0.9995, 1999), [1.0]])
    q = np.quantile(v, p)
    q[0], q[-1] = v[0], v[-1]
    for i in range(1, len(q)):
        q[i] = max(q[i], q[i - 1] + 1e-12)
    doc = {"meta": {"seed": SEED_LAW, "N_law": int(v.size), "n_law": N_LAW_N,
                    "wall_clock_s": round(time.time() - t0, 1),
                    "script": "code/gen_t12_law.py",
                    "ks_resolution": round(1.358 / float(np.sqrt(v.size)), 5),
                    "note": ("Independent realisation of the limit law of the scaled "
                             "Hoeffding statistic (T12), used as the full-distribution "
                             "reference for the KS distance. Monotone and normalised by "
                             "construction; its Monte Carlo error enters the reported "
                             "D_KS and is stated in the manuscript.")},
           "p_grid": p.tolist(), "z_grid": q.tolist()}
    path = os.path.join(OUT_DIR, "rev_results_t12_law.json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(doc, fh, indent=1)
    print(f"wrote {path}  N={v.size} n_law={N_LAW_N}  ({doc['meta']['wall_clock_s']}s)")


def build_diag():
    """Write ``rev_results_t12_diag.json`` from the committed reference."""
    rows = []
    for n in NS_DIAG:
        sv = core.mc_hoeffding_d(n, N_DIAG, dep="indep",
                                 rng=np.random.default_rng(SEED_DIAG))
        sv = sv[np.isfinite(sv)]
        sv.sort()
        emp = np.arange(1, len(sv) + 1) / len(sv)
        ev = core._evaluate(sv, "T12_hoeffding_d", alpha=0.05, n=n)
        rows.append({"n": n,
                     "ks_law": float(core.ks_distance(sv, "hoeffding_law")),
                     # Software diagnostic only: the published table is not a distribution function, so this
                     # number is not a distance to a probability law (see the note in core.hoeffding_z_sf).
                     "ks_tab": float(core.ks_distance(sv, "hoeffding_z")),
                     "ks_norm": float(np.max(np.abs(emp - st.norm.cdf(sv)))),
                     "a05": float(ev["type1"]),
                     "a01": float(core._evaluate(sv, "T12_hoeffding_d", 0.01, n=n)["type1"]),
                     "a10": float(core._evaluate(sv, "T12_hoeffding_d", 0.10, n=n)["type1"]),
                     "crit": float(ev["critical_value"])})
    path = os.path.join(OUT_DIR, "rev_results_t12_diag.json")
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(rows, fh, indent=1)
    print(f"wrote {path} ({len(rows)} rows)")


def main():
    """Run the requested stages."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--outdir", default=None,
                    help="directory for results files (default: the package root)")
    ap.add_argument("--diag-only", action="store_true",
                    help="reuse the committed reference and rebuild only the diagnostic")
    args = ap.parse_args()
    if args.outdir:
        _apply_outdir(args.outdir)
    if not args.diag_only:
        build_law()
    else:
        core._HOEFFD_LAW = core._load_hoeffding_law()
    build_diag()


if __name__ == "__main__":
    main()
