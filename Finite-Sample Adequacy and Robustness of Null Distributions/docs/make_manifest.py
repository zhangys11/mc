#!/usr/bin/env python3
"""Write and verify a SHA-256 manifest of the reproducibility package.

The manifest covers the *inputs and results* of the package: the analysis scripts, the
results files they produce, the pinned environment, the documentation and the figures.
It deliberately does NOT cover ``draft.md``, ``response_letter.md`` or their PDFs, which
are built artefacts: they are regenerated by ``build.sh`` from the manuscript sources and
would change on every edit, so hashing them would make the manifest a build log rather
than a reproducibility check.  The link from the results files to the numbers quoted in
the manuscript is verified instead by ``code/verify_manuscript.py``, which re-derives
every quoted value from the results file that produced it.

Usage (from the repository root)::

    python3 docs/make_manifest.py            # write docs/MANIFEST.sha256
    python3 docs/make_manifest.py --check    # verify the working tree against it
    python3 docs/make_manifest.py --lock     # check the environment against
                                             # requirements-lock.txt

The manifest covers every Python source file of the simulation (``code/``),
every results file (JSON) and published figure (PNG), the package-root
environment records, and the documentation tooling in ``docs/``. Superseded
submission material in ``archive/`` is excluded on purpose.  It lets a reader
confirm in one command that a downloaded copy is byte-identical to the copy that
produced the manuscript, which is the strongest form of the referee's
"reproducible by independent researchers" request that a file listing can give.

Author: t4-docs (task-4).
"""

from __future__ import annotations

import hashlib
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "docs", "MANIFEST.sha256")

SKIP_DIRS = {"__pycache__", ".git", "docs", "R1"}


def sha256(path: str) -> str:
    """SHA-256 of a file, read in 1 MiB chunks (works for large PNGs too)."""
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def targets() -> list[str]:
    """Repository files to hash: pipeline sources, results, figures and docs tools.

    Two layouts are supported, because the same verification code runs in both.  In the
    **submission layout** the results sit at the package root beside the manuscript and
    the response letter; in the **repository layout** the results sit in ``results/`` and
    the submission documents are absent, since they are not distributed publicly.  The
    directories scanned below cover both.
    """

    out = []

    def consider(rel: str) -> None:
        name = os.path.basename(rel)
        if name.startswith(".") or name.endswith("_quick.json"):
            # _quick.json is a smoke-run artefact of `rev_study1_ext.py --quick`
            return
        if name.endswith((".py", ".json", ".sh", ".tex")) or name.startswith("fig_") or \
                name in ("requirements.txt", "requirements-lock.txt"):
            out.append(rel)

    for sub in ("", "code", "figures", "results"):
        base = os.path.join(ROOT, sub) if sub else ROOT
        if not os.path.isdir(base):
            continue        # layout-dependent: results/ exists only in the repository copy
        for name in sorted(os.listdir(base)):
            full = os.path.join(base, name)
            if not os.path.isfile(full):
                continue
            consider(os.path.join(sub, name) if sub else name)

    # The frozen original-submission script and its driver, when they are present: in the
    # repository copy experiments.py sits at the package root beside the manuscript-facing
    # record, and build.sh / latex_preamble.tex exist only in the submission copy.
    for name in ("experiments.py", "build.sh", "latex_preamble.tex"):
        if os.path.exists(os.path.join(ROOT, name)):
            out.append(name)

    # the verification and documentation tools shipped in docs/, plus the two
    # environment records and the rendered flowchart panel.  Excluded on purpose:
    # docs/MANIFEST.sha256 (this file) and docs/verification_log.txt (rewritten by
    # every run of docs/run_verification.sh), and the Markdown documents, which are
    # prose rather than reproducible artefacts.
    docs_keep = {"ENVIRONMENT.txt", "pip_freeze_full.txt",
                 "fig_execution_flow.png", "fig_execution_flow.pdf"}
    for name in sorted(os.listdir(os.path.join(ROOT, "docs"))):
        full = os.path.join(ROOT, "docs", name)
        if not os.path.isfile(full):
            continue
        if name.endswith((".py", ".sh", ".mmd")) or name in docs_keep:
            out.append(os.path.join("docs", name))
    return out


def write_manifest() -> int:
    """Hash every pipeline source, result and figure; write docs/MANIFEST.sha256."""
    lines = [
        "# SHA-256 manifest of the mc-tk reproducibility package",
        "# COST-D-26-00503R1 (Computational Statistics, major revision).",
        "#",
        "# Regenerate with : python3 docs/make_manifest.py",
        "# Verify with     : python3 docs/make_manifest.py --check",
        "#",
        "# Covers every Python source, results JSON, figure, build script and LaTeX",
        "# preamble in the repository root, plus the tools, environment records and",
        "# rendered flowchart in docs/.  Excluded on purpose: this manifest itself, the",
        "# verification log (rewritten by every run) and the Markdown documents;",
        "# smoke-run artefacts (`*_quick.json`) are reduced-budget development output.",
        "#",
        "# Format: <sha256>  <relative path>",
        "",
    ]
    for name in targets():
        lines.append(f"{sha256(os.path.join(ROOT, name))}  {name}")
    with open(MANIFEST, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {MANIFEST} ({len(targets())} files)")
    return 0


def layout() -> str:
    """Detect which of the two supported layouts this package copy uses.

    Returns:
        str: ``"repository"`` when results live in ``results/`` (the public repository
        copy, which does not ship the submission documents), otherwise ``"submission"``.
    """
    return "repository" if os.path.isdir(os.path.join(ROOT, "results")) else "submission"


def check_manifest() -> int:
    """Compare the working tree with docs/MANIFEST.sha256; return 0 when identical."""
    bad, missing, changed = [], [], []
    with open(MANIFEST) as fh:
        entries = [ln.split(None, 1) for ln in fh
                   if ln.strip() and not ln.startswith("#")]
    for digest, name in entries:
        name = name.strip()
        full = os.path.join(ROOT, name)
        if not os.path.exists(full):
            missing.append(name)
        elif sha256(full) != digest:
            changed.append(name)
    listed = {n.strip() for _, n in entries}
    for name in targets():
        if name not in listed:
            bad.append(name)
    ok = not (missing or changed or bad)
    print(f"manifest entries : {len(entries)}")
    print(f"missing          : {missing or 'none'}")
    print(f"changed          : {changed or 'none'}")
    print(f"unlisted new     : {bad or 'none'}")
    print("MANIFEST " + ("OK" if ok else "MISMATCH"))
    return 0 if ok else 1


def check_lock() -> int:
    """Confirm that the installed environment matches requirements-lock.txt."""
    lock = os.path.join(ROOT, "requirements-lock.txt")
    wanted = {}
    with open(lock) as fh:
        for ln in fh:
            ln = ln.strip()
            if ln and not ln.startswith("#") and "==" in ln:
                name, _, ver = ln.partition("==")
                wanted[name.lower().replace("_", "-")] = ver
    frozen = subprocess.run([sys.executable, "-m", "pip", "freeze"],
                            capture_output=True, text=True).stdout
    have = {}
    for ln in frozen.splitlines():
        if "==" in ln and " @ " not in ln:
            name, _, ver = ln.partition("==")
            have[name.lower().replace("_", "-")] = ver
    mismatched = {k: (v, have.get(k)) for k, v in wanted.items()
                  if have.get(k) != v}
    print(f"lock entries checked : {len(wanted)}")
    for k, (want, got) in mismatched.items():
        print(f"  MISMATCH {k}: lock says {want}, environment has {got}")
    print("requirements-lock.txt " + ("OK" if not mismatched else "MISMATCH"))
    return 0 if not mismatched else 1


if __name__ == "__main__":
    if "--check" in sys.argv:
        sys.exit(check_manifest())
    if "--lock" in sys.argv:
        sys.exit(check_lock())
    sys.exit(write_manifest())
